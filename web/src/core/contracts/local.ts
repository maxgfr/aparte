/*
 * Contracts of the on-device model layer (milestone M4): models that run in this browser (WebLLM over WebGPU, in a
 * worker; Chrome's built-in Prompt API) and the embeddings runtime (transformers.js over ONNX Runtime WebAssembly, in a
 * worker). Implemented by web/src/core/ai/local/*.ts; the workers are web/src/workers/webllm.worker.ts and
 * web/src/workers/transformers.worker.ts. Local servers (Ollama, LM Studio, Jan) are OpenAI-compatible providers
 * (web/src/core/ai/endpoints.ts); only their diagnosis lives here (diagnose.ts).
 *
 * Invariants:
 * - Code and weights fetched at runtime are pinned: WebLLM model files are read from Hugging Face at a fixed commit
 *   (`resolve/<commit>/`), model libraries from mlc-ai/binary-mlc-llm-libs at a fixed commit, the embedding model at a
 *   fixed revision, and every byte is checked against a SHA-256 shipped with the app before it is cached and again
 *   when it is first read back in a worker's life (CacheStorage is shared with every app of the origin). A URL without
 *   a digest is refused.
 * - The workers have no network of their own: their `fetch` is replaced, before any library runs, by one that admits
 *   only pinned URLs and sends them through web/src/security/net.ts (purpose `download`, or `app` for the app's own
 *   ONNX Runtime files). Everything else is refused, so a library cannot reach a host the app does not know.
 * - Nothing about a conversation is stored: prompts and answers only cross the worker boundary in memory. Caches hold
 *   public model files only, under names starting with `aparte-`.
 * - A chat never downloads: a model that is not fully on this device fails with `not-downloaded`. Downloads start only
 *   from the model screen, after a storage check, and can be stopped (what was fetched stays and the next download
 *   resumes) or deleted.
 * - On lock, the engines are stopped (the workers terminate), so no conversation state outlives the vault session.
 */

import type { ChatAdapter } from './ai.ts'

// Errors

export type LocalErrorCode =
  /** The model is not one this build pins. */
  | 'unsupported-model'
  /** Its files are not all on this device: download it from the model screen first. */
  | 'not-downloaded'
  /** The download would not fit next to the vault's data. */
  | 'no-space'
  /** A file did not match its pinned SHA-256. */
  | 'integrity'
  /** A library asked for a URL that is not pinned. */
  | 'unpinned'
  /** This browser cannot run the model (no WebGPU, no Prompt API, too little memory). */
  | 'unavailable'
  /** The engine failed (GPU lost, out of memory, a worker crash). */
  | 'engine'

export const LOCAL_ERROR_CODES: readonly LocalErrorCode[] = [
  'unsupported-model',
  'not-downloaded',
  'no-space',
  'integrity',
  'unpinned',
  'unavailable',
  'engine',
]

export class LocalModelError extends Error {
  constructor(
    readonly code: LocalErrorCode,
    message: string,
  ) {
    super(message)
    this.name = 'LocalModelError'
  }
}

// Pinned WebLLM models (web/src/core/ai/local/webllm-models.json, generated by web/scripts/pin-local-models.ts)

export interface PinnedModel {
  /** WebLLM's model id (`Qwen3.5-0.8B-q4f16_1-MLC`). */
  readonly id: string
  readonly name: string
  readonly series: string
  /** Hugging Face repository (`mlc-ai/<id>`). */
  readonly repo: string
  /** The commit every file is read at. */
  readonly commit: string
  /** The compiled WebGPU library, at a fixed commit of mlc-ai/binary-mlc-llm-libs. */
  readonly lib: { readonly url: string; readonly sha256: string; readonly bytes: number }
  /** Everything a download may fetch, library included (an upper bound). */
  readonly bytes: number
  /** GPU memory it needs, as WebLLM publishes it. */
  readonly vramMB: number
  readonly contextWindow: number
  /** Function calling (WebLLM supports it on some Hermes models only). */
  readonly tools: boolean
  /** It thinks before answering (`<think>` blocks). */
  readonly reasoning: boolean
  /** Needs the `shader-f16` GPU feature. */
  readonly f16: boolean
  /** Runs within a 128 MiB storage-buffer binding. */
  readonly lowResource: boolean
}

// Device

/** The parts of a WebGPU adapter the device check reads (structural, so tests and e2e can fake it). */
export interface AdapterLike {
  readonly limits: {
    readonly maxBufferSize: number
    readonly maxStorageBufferBindingSize: number
    readonly maxComputeWorkgroupStorageSize: number
  }
  readonly features: { has(name: string): boolean }
  readonly info?: { readonly vendor?: string }
}

export interface GpuLike {
  requestAdapter(options?: { powerPreference?: 'high-performance' | 'low-power' }): Promise<AdapterLike | null>
}

export interface GpuReport {
  readonly vendor: string
  readonly shaderF16: boolean
  /** RAM the browser reports (Chromium, rounded and capped at 8 GiB), or null. */
  readonly deviceMemoryGiB: number | null
  /** GPU memory a model may take, estimated: WebGPU does not expose it. */
  readonly memoryBudgetMB: number
  /** Storage bindings under 1 GiB: only low-resource builds load. */
  readonly lowResource: boolean
}

export type DeviceVerdict =
  | { readonly supported: true; readonly gpu: GpuReport }
  | {
      readonly supported: false
      readonly reason: 'no-webgpu' | 'no-adapter' | 'too-little-memory'
      readonly gpu?: GpuReport
    }

/** What the origin uses and may use (`navigator.storage.estimate()`). */
export interface StorageEstimate {
  readonly usage?: number
  readonly quota?: number
}

export type SpaceVerdict =
  | { readonly ok: true; readonly needBytes: number; readonly freeBytes: number }
  | { readonly ok: false; readonly reason: 'unknown' }
  | { readonly ok: false; readonly reason: 'not-enough-space'; readonly needBytes: number; readonly freeBytes: number }

/** What of a model is on this device. */
export interface ModelCacheState {
  /** Every pinned file is cached: the model runs offline. */
  readonly complete: boolean
  readonly cachedBytes: number
  readonly totalBytes: number
}

// Engine (the WebLLM worker, seen from the page)

export interface LoadProgress {
  /** 0 to 1: download, then upload to the GPU. */
  readonly fraction: number
  /** The engine's own line, in English (shown as a detail only). */
  readonly text: string
}

/** One message as the engine takes it (OpenAI chat completions). */
export type EngineMessage =
  | { readonly role: 'system' | 'user'; readonly content: string }
  | {
      readonly role: 'assistant'
      readonly content: string
      readonly tool_calls?: readonly {
        readonly id: string
        readonly type: 'function'
        readonly function: { readonly name: string; readonly arguments: string }
      }[]
    }
  | { readonly role: 'tool'; readonly content: string; readonly tool_call_id: string }

export interface EngineTool {
  readonly type: 'function'
  readonly function: { readonly name: string; readonly description: string; readonly parameters: unknown }
}

export interface EngineChatRequest {
  readonly modelId: string
  readonly messages: readonly EngineMessage[]
  readonly tools?: readonly EngineTool[]
  readonly maxTokens?: number
  readonly temperature?: number
  readonly topP?: number
  readonly presencePenalty?: number
  readonly frequencyPenalty?: number
  readonly seed?: number
}

/** What the engine streams back for one chat request, in order; exactly one `done` unless it fails or is aborted. */
export type EngineChunk =
  | { readonly type: 'delta'; readonly text: string }
  | {
      readonly type: 'done'
      /** OpenAI's finish reason: `stop`, `length`, `tool_calls`, `abort`. */
      readonly finish: string
      readonly usage?: { readonly input: number; readonly output: number }
      readonly toolCalls?: readonly { readonly id: string; readonly name: string; readonly arguments: string }[]
    }

export interface LoadOptions {
  /** Fetch what the cache lacks; without it, a model not fully cached fails with `not-downloaded`. */
  readonly download: boolean
  readonly onProgress?: (p: LoadProgress) => void
  readonly signal?: AbortSignal
}

export interface LocalEngine {
  /** Loads a pinned model (one at a time). Aborting stops the worker: the files fetched so far stay. */
  load(modelId: string, options: LoadOptions): Promise<void>
  /** Streams one answer of the loaded model; aborting interrupts the generation. */
  chat(request: EngineChatRequest, signal: AbortSignal): AsyncIterable<EngineChunk>
  /** Terminates the worker and frees its GPU memory. */
  dispose(): void
}

// Chrome's Prompt API (`LanguageModel`), structurally

export type PromptAvailability = 'unavailable' | 'downloadable' | 'downloading' | 'available'

export interface PromptSessionLike {
  promptStreaming(input: string, options?: { signal?: AbortSignal }): ReadableStream<string> | AsyncIterable<string>
  destroy(): void
  readonly inputUsage?: number
}

export interface PromptOptions {
  readonly initialPrompts?: readonly { role: 'system' | 'user' | 'assistant'; content: string }[]
  readonly signal?: AbortSignal
  readonly monitor?: (m: EventTarget) => void
  readonly expectedInputs?: readonly { type: 'text'; languages?: readonly string[] }[]
  readonly expectedOutputs?: readonly { type: 'text'; languages?: readonly string[] }[]
}

export interface LanguageModelLike {
  availability(options?: Pick<PromptOptions, 'expectedInputs' | 'expectedOutputs'>): Promise<PromptAvailability>
  create(options?: PromptOptions): Promise<PromptSessionLike>
}

